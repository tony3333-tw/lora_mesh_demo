%% Regenerate include/ from proto/:
%%   1. gpb writes one records .hrl for every message (via proto/meshtastic.proto)
%%   2. it is split into one .hrl per .proto file, each including the
%%      .hrl files of the .proto files it imports.
%%
%% From the project root, with gpb on the code path:
%%   erlc -o tools tools/split_hrl.erl
%%   erl -noshell -pa tools -pa <gpb>/ebin -eval 'split_hrl:all(), halt().'
-module(split_hrl).
-export([all/0]).
-export([run/3]).

-define(GPB_OPTS,
        [use_packages,
         {rename, {msg_name, snake_case}},
         {rename, {msg_name, dots_to_underscores}},
         {rename, {msg_fqname, base_name}}]).

all() ->
    ok = filelib:ensure_dir("_gen/x"),
    ok = gpb_compile:file("meshtastic.proto",
                          [{i, "proto"},
                           {o, "_gen"},
                           {strings_as_binaries, true},
                           type_specs,
                           defs_as_maps,
                           {module_name_suffix, "_pb"},
                           report_errors
                           | ?GPB_OPTS]),
    run("proto", "_gen/meshtastic_pb.hrl", "include").

run(ProtoDir, BigHrl, OutDir) ->
    Opts = [{i, ProtoDir},
            to_proto_defs,
            {proto_defs_version, 4}
            | ?GPB_OPTS],
    {ok, Defs} = gpb_compile:file("meshtastic.proto", Opts),
    Blocks = record_blocks(BigHrl),
    Files = [{Base, Msgs}
             || {{msg_containment, Base}, Msgs} <- Defs,
                Base =/= "meshtastic"],
    Enums = [{Base, Es} || {{enum_containment, Base}, Es} <- Defs],
    Written = [write_one(ProtoDir, OutDir, Base, Msgs,
                         proplists:get_value(Base, Enums, []), Blocks)
               || {Base, Msgs} <- Files],
    write_all(OutDir, [P || P <- Written, lists:prefix("meshtastic/", P)]),
    io:format("wrote ~p files, ~p records~n",
              [length(Written) + 1,
               lists:sum([length(M) || {_, M} <- Files])]).

%% "-ifndef('X_PB_H'). ... -record(name, ...). -endif." blocks by record name
record_blocks(File) ->
    {ok, Bin} = file:read_file(File),
    {match, Ms} = re:run(Bin,
                         "-ifndef\\('[A-Z0-9_]+_PB_H'\\)\\.\\n"
                         "-define\\([^\\n]+\\n"
                         "-record\\(([a-z0-9_]+),.*?\\n-endif\\.\\n",
                         [global, dotall, {capture, [0, 1], binary}]),
    maps:from_list([{binary_to_atom(Name), Block} || [Block, Name] <- Ms]).

%% Where each .proto's .hrl goes, relative to OutDir
rel_path("descriptor") -> "google/protobuf/descriptor.hrl";
rel_path("nanopb")     -> "nanopb.hrl";
rel_path(Base)         -> "meshtastic/" ++ Base ++ ".hrl".

proto_path(_ProtoDir, "descriptor") -> undefined;
proto_path(ProtoDir, "nanopb") -> filename:join(ProtoDir, "nanopb.proto");
proto_path(ProtoDir, Base) ->
    filename:join([ProtoDir, "meshtastic", Base ++ ".proto"]).

imports(undefined) ->
    [];
imports(ProtoFile) ->
    {ok, Bin} = file:read_file(ProtoFile),
    case re:run(Bin, "^import \"([^\"]+)\\.proto\";",
                [global, multiline, {capture, [1], list}]) of
        {match, Ms} -> [filename:basename(I) || [I] <- Ms];
        nomatch     -> []
    end.

write_one(ProtoDir, OutDir, Base, Msgs, Enums, Blocks) ->
    Rel = rel_path(Base),
    Here = filename:dirname(Rel),
    Includes = [["-include(\"", relative(Here, rel_path(I)), "\").\n"]
                || I <- imports(proto_path(ProtoDir, Base))],
    Guard = string:uppercase(re:replace(Rel, "[/.]", "_",
                                        [global, {return, list}])),
    Src = case Base of
              "descriptor" -> "google/protobuf/descriptor.proto";
              "nanopb"     -> "nanopb.proto";
              _            -> "meshtastic/" ++ Base ++ ".proto"
          end,
    EnumLines = [io_lib:format("%%   ~s~n", [E]) || E <- Enums],
    Body = [maps:get(M, Blocks) || M <- Msgs],
    Text = ["%% -*- coding: utf-8 -*-\n",
            "%% Records for ", Src, "\n",
            "%% Generated by gpb 5.0.0 (record mode), split per .proto file.\n",
            "%% Do not edit by hand: regenerate from the .proto files.\n",
            "%%\n",
            "%% Records: ", integer_to_list(length(Msgs)), "\n",
            case Enums of
                [] -> "";
                _  -> ["%% Enums (values are atoms in record fields):\n",
                       EnumLines]
            end,
            "\n-ifndef(", Guard, ").\n",
            "-define(", Guard, ", true).\n\n",
            Includes,
            case Includes of [] -> ""; _ -> "\n" end,
            Body,
            "\n-endif.\n"],
    Path = filename:join(OutDir, Rel),
    ok = filelib:ensure_dir(Path),
    ok = file:write_file(Path, Text),
    Rel.

write_all(OutDir, Rels) ->
    Text = ["%% -*- coding: utf-8 -*-\n",
            "%% Every Meshtastic record: includes one .hrl per .proto file.\n\n",
            "-ifndef(MESHTASTIC_ALL_HRL).\n",
            "-define(MESHTASTIC_ALL_HRL, true).\n\n",
            [["-include(\"", R, "\").\n"] || R <- lists:sort(Rels)],
            "\n-endif.\n"],
    ok = file:write_file(filename:join(OutDir, "meshtastic_all.hrl"), Text).

%% path of To relative to directory From (both relative to OutDir)
relative(From, To) ->
    FromParts = case From of "." -> []; _ -> filename:split(From) end,
    ToParts = filename:split(To),
    {F, T} = drop_common(FromParts, ToParts),
    filename:join([".." || _ <- F] ++ T).

drop_common([X | A], [X | B]) -> drop_common(A, B);
drop_common(A, B) -> {A, B}.
